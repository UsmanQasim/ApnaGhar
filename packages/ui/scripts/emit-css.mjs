#!/usr/bin/env node
/**
 * Emit the design tokens as CSS.
 *
 * `tokens.ts` is the source of truth and always has been — the React Native
 * app consumes it directly. The web apps now need the same values as CSS
 * custom properties so Tailwind can build utilities from them, and a
 * hand-maintained second copy is exactly the drift the token system exists to
 * prevent (see the note at the top of tokens.ts).
 *
 * So: generated, committed, and checked. `tokens.test.ts` regenerates into a
 * temp directory and diffs, failing if the committed files are stale — which
 * turns "someone changed a colour and forgot the CSS" from a silent visual bug
 * into a red test.
 *
 * Two outputs:
 *   tokens.css         — plain custom properties, framework-agnostic.
 *   tailwind-theme.css — the Tailwind v4 @theme block mapping them onto
 *                        utility namespaces, so `bg-primary` and `rounded-lg`
 *                        mean the token, not Tailwind's default.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, '..');

const { colors, roles, chart, spacing, radius, webFontStack, webLineHeight } = await import(
  join(pkg, 'dist', 'tokens.js')
);

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const radiusKey = (name) => (name === 'DEFAULT' ? 'default' : kebab(name));

export function buildTokensCss() {
  const lines = [
    '/* GENERATED by scripts/emit-css.mjs — do not edit by hand.',
    ' * Source of truth is src/tokens.ts. Run `pnpm --filter @ghar/ui build`.',
    ' */',
    ':root {',
    '  /* Colours */',
  ];

  for (const [name, value] of Object.entries(colors)) {
    lines.push(`  --ghar-color-${kebab(name)}: ${value};`);
  }

  lines.push('', '  /* Semantic roles */');
  for (const [name, value] of Object.entries(roles)) {
    lines.push(`  --ghar-role-${kebab(name)}: ${value};`);
  }

  lines.push('', '  /* Chart series */');
  for (const [name, value] of Object.entries(chart)) {
    lines.push(`  --ghar-chart-${kebab(name)}: ${value};`);
  }

  lines.push('', '  /* Spacing (px — the scale is deliberately small and fixed) */');
  for (const [name, value] of Object.entries(spacing)) {
    lines.push(`  --ghar-space-${kebab(name)}: ${value}px;`);
  }

  lines.push('', '  /* Radii */');
  for (const [name, value] of Object.entries(radius)) {
    lines.push(`  --ghar-radius-${radiusKey(name)}: ${value}px;`);
  }

  lines.push('', '  /* Script-dependent type. The <html> element picks one. */');
  for (const [name, value] of Object.entries(webFontStack)) {
    lines.push(`  --ghar-font-${name}: ${value};`);
  }
  for (const [name, value] of Object.entries(webLineHeight)) {
    lines.push(`  --ghar-leading-${name}: ${value};`);
  }

  lines.push('}', '');
  return lines.join('\n');
}

export function buildThemeCss() {
  const lines = [
    '/* GENERATED by scripts/emit-css.mjs — do not edit by hand. */',
    "@import './tokens.css';",
    '',
    '/*',
    ' * Tailwind v4 reads its scales from @theme. `inline` means the utilities',
    ' * resolve to the var() rather than copying the value, so a token change',
    ' * flows through without rewriting every class.',
    ' *',
    " * Only OUR names are declared here. Tailwind's stock palette stays",
    ' * available, but nothing in these apps should reach for it: a colour that',
    ' * exists in two places eventually exists in two different values.',
    ' */',
    '@theme inline {',
  ];

  for (const name of Object.keys(colors)) {
    lines.push(`  --color-${kebab(name)}: var(--ghar-color-${kebab(name)});`);
  }
  for (const name of Object.keys(roles)) {
    lines.push(`  --color-${kebab(name)}: var(--ghar-role-${kebab(name)});`);
  }
  for (const name of Object.keys(chart)) {
    lines.push(`  --color-chart-${kebab(name)}: var(--ghar-chart-${kebab(name)});`);
  }

  lines.push('');
  for (const name of Object.keys(spacing)) {
    lines.push(`  --spacing-${kebab(name)}: var(--ghar-space-${kebab(name)});`);
  }

  lines.push('');
  for (const name of Object.keys(radius)) {
    lines.push(`  --radius-${radiusKey(name)}: var(--ghar-radius-${radiusKey(name)});`);
  }

  lines.push('}', '');
  return lines.join('\n');
}

// The test regenerates into a temp directory and diffs against the committed
// files, so it needs somewhere else to write.
const outDir = process.env['EMIT_CSS_OUT'] ?? pkg;

writeFileSync(join(outDir, 'tokens.css'), buildTokensCss(), 'utf8');
writeFileSync(join(outDir, 'tailwind-theme.css'), buildThemeCss(), 'utf8');

if (!process.env['EMIT_CSS_OUT']) {
  console.log('✓ wrote packages/ui/tokens.css and tailwind-theme.css');
}
